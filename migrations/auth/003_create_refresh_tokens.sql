CREATE TABLE IF NOT EXISTS refresh_tokens (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id      INTEGER NOT NULL REFERENCES auth_sessions (id) ON DELETE CASCADE,
    token_hash      TEXT NOT NULL,
    parent_token_id INTEGER REFERENCES refresh_tokens (id) ON DELETE SET NULL,
    replaced_by_id  INTEGER REFERENCES refresh_tokens (id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ NOT NULL,
    used_at         TIMESTAMPTZ,
    revoked_at      TIMESTAMPTZ,
    CONSTRAINT refresh_tokens_expiry_chk CHECK (expires_at > created_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS refresh_tokens_token_hash_uidx
    ON refresh_tokens (token_hash);

